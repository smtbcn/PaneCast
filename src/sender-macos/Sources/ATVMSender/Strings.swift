extension L10n {
    /// Rozet/başlık yazısı: **büyük harf Türkçe kurallarıyla** çözülür.
    /// `uppercased()` yerel duyarsızdır: "Keşif" → "KEŞIF" olurdu, doğrusu "KEŞİF".
    static func caps(_ key: TextKey) -> String {
        let locale = Locale(identifier: isEnglish ? "en" : "tr")
        return t(key).uppercased(with: locale)
    }
}
